/**
 * HREFLANG IMPLEMENTATION
 * Add to <head> of each page
 */
export const getHrefLangTags = (currentLocale: string, pathname: string) => {
  const baseUrl = 'https://www.alidrisy.com';
  const path = pathname.replace(/^\/(en|ar)/, '');

  return `
    <!-- Hreflang Tags for Internationalization -->
    <link rel="alternate" hrefLang="en" href="${baseUrl}/en${path}" />
    <link rel="alternate" hrefLang="ar" href="${baseUrl}/ar${path}" />
    <link rel="alternate" hrefLang="x-default" href="${baseUrl}${path}" />
  `;
};

/**
 * CANONICAL URL PATTERN
 * For each locale page
 */
export const getCanonicalUrl = (locale: string, pathname: string): string => {
  const baseUrl = 'https://www.alidrisy.com';
  const path = pathname.replace(/^\/(en|ar)/, '');
  return `${baseUrl}/${locale}${path}`;
};

